-- Online-SPC 开发态 DDL (SQLite)
-- 与 src/Spc.Infrastructure/DbNaming.cs 的 PascalCase -> UPPER_SNAKE_CASE 映射严格对应
-- 规格限 USL/LSL 只存在于 SPC_CHART；控制限只存在于 SPC_LIMIT_VERSION（方案 4.5 / 7.2）

CREATE TABLE IF NOT EXISTS SPC_CHART (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  CODE           TEXT NOT NULL UNIQUE,
  NAME           TEXT NOT NULL,
  CHART_TYPE     INTEGER NOT NULL,
  SUBGROUP_SIZE  INTEGER NOT NULL,
  USL            REAL NULL,
  LSL            REAL NULL,
  TARGET         REAL NULL,
  UNIT           TEXT NOT NULL DEFAULT 'mm',
  MACHINE        TEXT NOT NULL,
  PRODUCT        TEXT NOT NULL,
  PROCESS        TEXT NOT NULL,
  RECIPE         TEXT NOT NULL,
  RULE_SET_VER   TEXT NOT NULL,
  IS_ENABLED     INTEGER NOT NULL DEFAULT 1,
  CREATED_AT     TEXT NOT NULL,
  UPDATED_AT     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS SPC_MEASURE (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  CHART_ID       INTEGER NOT NULL,
  EVENT_TIME     TEXT NOT NULL,
  MEASURE_VALUE  REAL NOT NULL,
  LOT_ID         TEXT NOT NULL,
  SN             TEXT NOT NULL,
  WORK_ORDER     TEXT NOT NULL,
  SHIFT          TEXT NOT NULL,
  RECIPE         TEXT NOT NULL,
  EQUIPMENT      TEXT NOT NULL,
  PROC_TAG       TEXT NOT NULL,
  SOURCE         INTEGER NOT NULL,
  DEDUP_KEY      TEXT NOT NULL UNIQUE,
  INGEST_TIME    TEXT NOT NULL,
  SUBGROUP_ID    INTEGER NULL
);

CREATE INDEX IF NOT EXISTS IX_SPC_MEASURE_CHART_TIME ON SPC_MEASURE (CHART_ID, EVENT_TIME);
CREATE INDEX IF NOT EXISTS IX_SPC_MEASURE_PENDING ON SPC_MEASURE (CHART_ID, SUBGROUP_ID, EVENT_TIME);

CREATE TABLE IF NOT EXISTS SPC_SUBGROUP (
  ID               INTEGER PRIMARY KEY AUTOINCREMENT,
  CHART_ID         INTEGER NOT NULL,
  SEQ              INTEGER NOT NULL,
  EVENT_TIME_FROM  TEXT NOT NULL,
  EVENT_TIME_TO    TEXT NOT NULL,
  SAMPLE_COUNT     INTEGER NOT NULL,
  XBAR             REAL NOT NULL,
  RANGE_VAL        REAL NOT NULL,
  STDDEV_VAL       REAL NOT NULL,
  MR_VAL           REAL NOT NULL,
  LIMIT_VER_ID     INTEGER NULL,
  STATUS           INTEGER NOT NULL,
  CLOSED_AT        TEXT NOT NULL,
  CREATED_AT       TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS UK_SPC_SUBGROUP_SEQ ON SPC_SUBGROUP (CHART_ID, SEQ);

-- 冻结限值版本：只 INSERT；发布时仅允许更新 STATUS / EFFECTIVE_FROM / EXPIRED_TIME
CREATE TABLE IF NOT EXISTS SPC_LIMIT_VERSION (
  ID              INTEGER PRIMARY KEY AUTOINCREMENT,
  CHART_ID        INTEGER NOT NULL,
  VERSION_NO      INTEGER NOT NULL,
  CHART_TYPE      INTEGER NOT NULL DEFAULT 1,
  CL              REAL NOT NULL,
  UCL             REAL NOT NULL,
  LCL             REAL NOT NULL,
  WARN_UCL        REAL NOT NULL,
  WARN_LCL        REAL NOT NULL,
  VAR_CL          REAL NOT NULL,
  VAR_UCL         REAL NOT NULL,
  VAR_LCL         REAL NOT NULL,
  SIGMA_HAT       REAL NOT NULL,
  SUBGROUP_SIZE   INTEGER NOT NULL,
  SUBGROUP_COUNT  INTEGER NOT NULL,
  DATA_FROM       TEXT NOT NULL,
  DATA_TO         TEXT NOT NULL,
  DATA_HASH       TEXT NOT NULL,
  SUBGROUP_IDS    TEXT NOT NULL,
  RULE_SET_VER    TEXT NOT NULL,
  CALC_PARAMS     TEXT NOT NULL,
  ITERATIONS      INTEGER NOT NULL,
  CHANGE_REASON   TEXT NOT NULL,
  CREATED_BY      TEXT NOT NULL,
  APPROVED_BY     TEXT NOT NULL,
  STATUS          INTEGER NOT NULL,
  EFFECTIVE_FROM  TEXT NULL,
  EXPIRED_TIME    TEXT NULL,
  CREATED_AT      TEXT NOT NULL
);

-- N-05：一张控制图同时只允许一个 ACTIVE 版本，数据库唯一索引兜底（SQLite 部分索引）
CREATE UNIQUE INDEX IF NOT EXISTS UK_SPC_LIMIT_ACTIVE ON SPC_LIMIT_VERSION (CHART_ID) WHERE STATUS = 3;
CREATE INDEX IF NOT EXISTS IX_SPC_LIMIT_HISTORY ON SPC_LIMIT_VERSION (CHART_ID, EFFECTIVE_FROM, EXPIRED_TIME);

CREATE TABLE IF NOT EXISTS SPC_BASELINE_EXCLUDE (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  CHART_ID       INTEGER NOT NULL,
  SUBGROUP_ID    INTEGER NOT NULL,
  SEQ            INTEGER NOT NULL,
  RULE_CODE      INTEGER NOT NULL,
  REASON         TEXT NOT NULL,
  CONFIRMED_BY   TEXT NOT NULL,
  CONFIRMED_AT   TEXT NOT NULL,
  ITERATION      INTEGER NOT NULL,
  CREATED_AT     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS SPC_RULE_OUT (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  CHART_ID       INTEGER NOT NULL,
  SUBGROUP_ID    INTEGER NOT NULL,
  LIMIT_VER_ID   INTEGER NOT NULL,
  RULE_CODE      INTEGER NOT NULL,
  SEVERITY       INTEGER NOT NULL,
  STAT_VALUE     REAL NOT NULL,
  Z_VALUE        REAL NOT NULL,
  EVENT_TIME     TEXT NOT NULL,
  OCAP_STATUS    INTEGER NOT NULL DEFAULT 1,
  LOT_ID         TEXT NOT NULL,
  SN             TEXT NOT NULL,
  CREATED_AT     TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS IX_SPC_RULE_OUT_CHART ON SPC_RULE_OUT (CHART_ID, EVENT_TIME);

CREATE TABLE IF NOT EXISTS SPC_OCAP (
  ID                         INTEGER PRIMARY KEY AUTOINCREMENT,
  RULE_OUT_ID                INTEGER NOT NULL,
  OCAP_NO                    TEXT NOT NULL,
  STATUS                     INTEGER NOT NULL,
  ASSIGNEE                   TEXT NOT NULL,
  CAUSE                      TEXT NOT NULL,
  COUNTERMEASURE             TEXT NOT NULL,
  DECISION                   TEXT NOT NULL,
  VERIFICATION_SUBGROUP_ID   INTEGER NULL,
  SIGNED_BY                  TEXT NOT NULL,
  DUE_TIME                   TEXT NULL,
  CLOSED_AT                  TEXT NULL,
  CREATED_AT                 TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS SPC_MES_ACTION (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  RULE_OUT_ID    INTEGER NOT NULL,
  ACTION_TYPE    INTEGER NOT NULL,
  STATUS         INTEGER NOT NULL,
  PAYLOAD        TEXT NOT NULL,
  MES_REF        TEXT NOT NULL,
  ACK_PAYLOAD    TEXT NOT NULL,
  REQUEST_TIME   TEXT NOT NULL,
  ACK_TIME       TEXT NULL,
  RETRY_COUNT    INTEGER NOT NULL DEFAULT 0,
  CREATED_AT     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS SPC_AUDIT_LOG (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  EVENT_TIME     TEXT NOT NULL,
  EVENT_TYPE     TEXT NOT NULL,
  ENTITY_TYPE    TEXT NOT NULL,
  ENTITY_ID      INTEGER NOT NULL,
  CHART_ID       INTEGER NOT NULL,
  PAYLOAD        TEXT NOT NULL,
  ACTOR          TEXT NOT NULL,
  CREATED_AT     TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS IX_SPC_AUDIT_CHART ON SPC_AUDIT_LOG (CHART_ID, EVENT_TIME);

-- M5 报表快照：定时/手工生成的日报周报月报与合规取证包（只增不改）
CREATE TABLE IF NOT EXISTS SPC_REPORT_SNAPSHOT (
  ID             INTEGER PRIMARY KEY AUTOINCREMENT,
  CHART_ID       INTEGER NOT NULL,
  REPORT_TYPE    TEXT NOT NULL,
  PERIOD_FROM    TEXT NOT NULL,
  PERIOD_TO      TEXT NOT NULL,
  PAYLOAD        TEXT NOT NULL,
  DATA_HASH      TEXT NOT NULL,
  GENERATED_BY   TEXT NOT NULL,
  GENERATED_AT   TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS IX_SPC_REPORT_CHART ON SPC_REPORT_SNAPSHOT (CHART_ID, GENERATED_AT);
