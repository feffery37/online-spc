);

CREATE INDEX IX_SPC_AUDIT_CHART ON SPC_AUDIT_LOG (CHART_ID, EVENT_TIME);

-- M5 报表快照：定时/手工生成的日报周报月报与合规取证包（只增不改）
CREATE TABLE SPC_REPORT_SNAPSHOT (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHART_ID       NUMBER NOT NULL,
  REPORT_TYPE    VARCHAR2(32) NOT NULL,
  PERIOD_FROM    TIMESTAMP NOT NULL,
  PERIOD_TO      TIMESTAMP NOT NULL,
  PAYLOAD        CLOB NOT NULL,
  DATA_HASH      VARCHAR2(64) NOT NULL,
  GENERATED_BY   VARCHAR2(64) NOT NULL,
  GENERATED_AT   TIMESTAMP NOT NULL
);

CREATE INDEX IX_SPC_REPORT_CHART ON SPC_REPORT_SNAPSHOT (CHART_ID, GENERATED_AT);
