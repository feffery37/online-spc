  DUE_TIME                   TIMESTAMP NULL,
  CLOSED_AT                  TIMESTAMP NULL,
  CREATED_AT                 TIMESTAMP NOT NULL
);

CREATE TABLE SPC_MES_ACTION (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RULE_OUT_ID    NUMBER NOT NULL,
  ACTION_TYPE    NUMBER(2) NOT NULL,
  STATUS         NUMBER(2) NOT NULL,
  PAYLOAD        VARCHAR2(2000) NOT NULL,
  MES_REF        VARCHAR2(64) NOT NULL,
  ACK_PAYLOAD    VARCHAR2(2000) NOT NULL,
  REQUEST_TIME   TIMESTAMP NOT NULL,
  ACK_TIME       TIMESTAMP NULL,
