-- Online-SPC 生产态 DDL (Oracle 12c+)
-- 与 src/Spc.Infrastructure/DbNaming.cs 的 PascalCase -> UPPER_SNAKE_CASE 映射严格对应
-- 规格限 USL/LSL 只存在于 SPC_CHART；控制限只存在于 SPC_LIMIT_VERSION（方案 4.5 / 7.2）
-- 生产建议：SPC_MEASURE 按 EVENT_TIME 做区间分区，原始点与统计值分表（方案 7.2 / 风险清单）

CREATE TABLE SPC_CHART (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE           VARCHAR2(64) NOT NULL UNIQUE,
  NAME           VARCHAR2(200) NOT NULL,
  CHART_TYPE     NUMBER(2) NOT NULL,
  SUBGROUP_SIZE  NUMBER(2) NOT NULL,
  USL            NUMBER(18,6) NULL,
  LSL            NUMBER(18,6) NULL,
  TARGET         NUMBER(18,6) NULL,
  UNIT           VARCHAR2(32) DEFAULT 'mm' NOT NULL,
  MACHINE        VARCHAR2(64) NOT NULL,
  PRODUCT        VARCHAR2(64) NOT NULL,
  PROCESS        VARCHAR2(64) NOT NULL,
  RECIPE         VARCHAR2(64) NOT NULL,
  RULE_SET_VER   VARCHAR2(64) NOT NULL,
  IS_ENABLED     NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_AT     TIMESTAMP NOT NULL,
  UPDATED_AT     TIMESTAMP NOT NULL
);

CREATE TABLE SPC_MEASURE (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHART_ID       NUMBER NOT NULL,
  EVENT_TIME     TIMESTAMP NOT NULL,
  MEASURE_VALUE  NUMBER(18,6) NOT NULL,
  LOT_ID         VARCHAR2(64) NOT NULL,
  SN             VARCHAR2(64) NOT NULL,
  WORK_ORDER     VARCHAR2(64) NOT NULL,
  SHIFT          VARCHAR2(32) NOT NULL,
  RECIPE         VARCHAR2(64) NOT NULL,
  EQUIPMENT      VARCHAR2(64) NOT NULL,
  PROC_TAG       VARCHAR2(2000) NOT NULL,
  SOURCE         NUMBER(2) NOT NULL,
  DEDUP_KEY      VARCHAR2(64) NOT NULL UNIQUE,
  INGEST_TIME    TIMESTAMP NOT NULL,
  SUBGROUP_ID    NUMBER NULL
);

CREATE INDEX IX_SPC_MEASURE_CHART_TIME ON SPC_MEASURE (CHART_ID, EVENT_TIME);
CREATE INDEX IX_SPC_MEASURE_PENDING ON SPC_MEASURE (CHART_ID, SUBGROUP_ID, EVENT_TIME);

CREATE TABLE SPC_SUBGROUP (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHART_ID         NUMBER NOT NULL,
  SEQ              NUMBER NOT NULL,
  EVENT_TIME_FROM  TIMESTAMP NOT NULL,
  EVENT_TIME_TO    TIMESTAMP NOT NULL,
  SAMPLE_COUNT     NUMBER(2) NOT NULL,
  XBAR             NUMBER(18,6) NOT NULL,
  RANGE_VAL        NUMBER(18,6) NOT NULL,
  STDDEV_VAL       NUMBER(18,6) NOT NULL,
  MR_VAL           NUMBER(18,6) NOT NULL,
  LIMIT_VER_ID     NUMBER NULL,
  STATUS           NUMBER(2) NOT NULL,
  CLOSED_AT        TIMESTAMP NOT NULL,
  CREATED_AT       TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX UK_SPC_SUBGROUP_SEQ ON SPC_SUBGROUP (CHART_ID, SEQ);

-- 冻结限值版本：只 INSERT；发布时仅允许更新 STATUS / EFFECTIVE_FROM / EXPIRED_TIME
CREATE TABLE SPC_LIMIT_VERSION (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHART_ID        NUMBER NOT NULL,
  VERSION_NO      NUMBER NOT NULL,
  CHART_TYPE      NUMBER(2) DEFAULT 1 NOT NULL,
  CL              NUMBER(18,8) NOT NULL,
  UCL             NUMBER(18,8) NOT NULL,
  LCL             NUMBER(18,8) NOT NULL,
  WARN_UCL        NUMBER(18,8) NOT NULL,
  WARN_LCL        NUMBER(18,8) NOT NULL,
  VAR_CL          NUMBER(18,8) NOT NULL,
  VAR_UCL         NUMBER(18,8) NOT NULL,
  VAR_LCL         NUMBER(18,8) NOT NULL,
  SIGMA_HAT       NUMBER(18,8) NOT NULL,
  SUBGROUP_SIZE   NUMBER(2) NOT NULL,
  SUBGROUP_COUNT  NUMBER NOT NULL,
  DATA_FROM       TIMESTAMP NOT NULL,
  DATA_TO         TIMESTAMP NOT NULL,
  DATA_HASH       VARCHAR2(64) NOT NULL,
  SUBGROUP_IDS    CLOB NOT NULL,
  RULE_SET_VER    VARCHAR2(64) NOT NULL,
  CALC_PARAMS     VARCHAR2(1000) NOT NULL,
  ITERATIONS      NUMBER(2) NOT NULL,
  CHANGE_REASON   VARCHAR2(500) NOT NULL,
  CREATED_BY      VARCHAR2(64) NOT NULL,
  APPROVED_BY     VARCHAR2(64) NOT NULL,
  STATUS          NUMBER(2) NOT NULL,
  EFFECTIVE_FROM  TIMESTAMP NULL,
  EXPIRED_TIME    TIMESTAMP NULL,
  CREATED_AT      TIMESTAMP NOT NULL
);

-- N-05：一张控制图同时只允许一个 ACTIVE 版本（方案 5.6 函数唯一索引）
CREATE UNIQUE INDEX UK_SPC_LIMIT_ACTIVE ON SPC_LIMIT_VERSION (DECODE(STATUS, 3, CHART_ID, NULL));
CREATE INDEX IX_SPC_LIMIT_HISTORY ON SPC_LIMIT_VERSION (CHART_ID, EFFECTIVE_FROM, EXPIRED_TIME);

CREATE TABLE SPC_BASELINE_EXCLUDE (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHART_ID       NUMBER NOT NULL,
  SUBGROUP_ID    NUMBER NOT NULL,
  SEQ            NUMBER NOT NULL,
  RULE_CODE      NUMBER(2) NOT NULL,
  REASON         VARCHAR2(500) NOT NULL,
  CONFIRMED_BY   VARCHAR2(64) NOT NULL,
  CONFIRMED_AT   TIMESTAMP NOT NULL,
  ITERATION      NUMBER(2) NOT NULL,
  CREATED_AT     TIMESTAMP NOT NULL
);

CREATE TABLE SPC_RULE_OUT (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHART_ID       NUMBER NOT NULL,
  SUBGROUP_ID    NUMBER NOT NULL,
  LIMIT_VER_ID   NUMBER NOT NULL,
  RULE_CODE      NUMBER(2) NOT NULL,
  SEVERITY       NUMBER(2) NOT NULL,
  STAT_VALUE     NUMBER(18,8) NOT NULL,
  Z_VALUE        NUMBER(18,8) NOT NULL,
  EVENT_TIME     TIMESTAMP NOT NULL,
  OCAP_STATUS    NUMBER(2) DEFAULT 1 NOT NULL,
  LOT_ID         VARCHAR2(64) NOT NULL,
  SN             VARCHAR2(64) NOT NULL,
  CREATED_AT     TIMESTAMP NOT NULL
